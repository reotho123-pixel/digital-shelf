/* ???????????????????????? ?????? Service Worker
   ???????????????????????????????????????????? CACHE ???????????? +1??????????????????????????????????????????????????????????????????????

   ??????????????????????????????? index.html?????????????????? app-prototype.html??????????????????
   ??????????????????????????????????????index.html ?????????????? /digital-shelf/ ??????????????????????????????????
   ????????????????????????????????????????????????????????? index.html????????????????????????????????????????????? */
const CACHE = 'digital-shelf-v36';

const ASSETS = [
  './',
  './index.html',
  './manifest.json',
  './fonts/zcoolkuaile.woff2',
  './fonts/kalam700.woff2',
  './fonts/patrickhand.woff2',
  './fonts/mashanzheng.woff2',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/apple-touch-icon.png'
];

// ?????????????????????????????????????????????? cache:'reload' ????????????????????????????????????? HTTP ???????????? ????????????
// GitHub Pages ?????????????????????????????????? max-age=600??????????????????????????????????????????????????????????????
// ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????KB??????
self.addEventListener('install', e => {
  e.waitUntil(
    caches.open(CACHE).then(c =>
      ASSETS.reduce((chain, url) =>
        chain.then(() => fetch(url, { cache: 'reload' }).then(res => {
          if (res && res.ok) return c.put(url, res);
        }).catch(() => {})), Promise.resolve())
    ).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== location.origin) return;   // ????????????????????

  // ?????????????????????????????????????????????????????????????????????????????????????????????????????
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then(res => {
          const copy = res.clone();
          caches.open(CACHE).then(c => c.put(req, copy)).catch(() => {});
          return res;
        })
        .catch(() => caches.match('./index.html').then(r => r || caches.match(req)))
    );
    return;
  }

  // ??????????????????????????????????????????????????????????????????????????????????????
  e.respondWith(
    caches.match(req).then(hit => {
      if (hit) return hit;
      return fetch(req).then(res => {
        if (res && res.status === 200 && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE).then(c => c.put(req, copy)).catch(() => {});
        }
        return res;
      }).catch(() => hit);
    })
  );
});
